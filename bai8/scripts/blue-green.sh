#!/usr/bin/env bash
# Blue/green deployment of the ShopFast API behind nginx (design: README section C).
#
#   blue-green.sh init <version>     first start: DB + migrations + 4 x <version> on blue + nginx
#   blue-green.sh deploy <version>   expand migration -> 4 x <version> on the idle color -> smoke test
#                                    -> switch nginx -> move realtime users -> old color stays as warm standby
#   blue-green.sh rollback           switch back to the previous color (restarts it first if already removed)
#   blue-green.sh finish             end of the observation window: stop the standby color (back to 4 containers)
#   blue-green.sh contract           next release: drop the old column once no container needs it
#   blue-green.sh status
set -euo pipefail
export MSYS_NO_PATHCONV=1 # Git Bash on Windows: do not rewrite /paths
cd "$(dirname "$0")/.."
[ -f .env ] && set -a && . ./.env && set +a
: "${DB_PASSWORD:?DB_PASSWORD is required (cp .env.example .env)}"

REPLICAS=${REPLICAS:-4}
LB_PORT=${LB_PORT:-8080}
PREVIEW_PORT=${PREVIEW_PORT:-8081}
STATE=.state
UPSTREAMS=nginx/generated/upstreams.conf
mkdir -p "$STATE" nginx/generated

log() { echo "[blue-green $(date +%H:%M:%S)] $*"; }
fail() { log "FAILED: $*"; exit 1; }
now_ms() { date +%s%3N; }
secs_since() { awk -v ms=$(($(now_ms) - $1)) 'BEGIN { printf "%.1f", ms / 1000 }'; }

get() { cat "$STATE/$1" 2>/dev/null || echo "${2:-}"; }
put() { echo "$2" >"$STATE/$1"; }
other() { [ "$1" = blue ] && echo green || echo blue; }

export BLUE_VERSION GREEN_VERSION
BLUE_VERSION=$(get blue.version v1)
GREEN_VERSION=$(get green.version v1)

compose() { docker compose "$@"; }
running() { compose ps -q --status running "app-$1" 2>/dev/null | grep -c . || true; }
app_containers() { echo $(($(running blue) + $(running green))); }
schema_target_of() { # schema target baked into an image (v1 -> 1, v2 -> 2)
  docker run --rm --entrypoint node "shopfast-bai8:$1" -e \
    "console.log(require('./dist/config').loadConfig({DATABASE_URL:'x', APP_VERSION:'$1'}).schemaTarget)"
}
served_version() { curl -s --max-time 2 "http://localhost:$1/version" | sed -n 's/.*"version":"\([^"]*\)".*/\1/p'; }

# ---- load balancer ------------------------------------------------------------------------------------------
write_upstreams() { # <live color> <preview color>
  cp "$UPSTREAMS" "$UPSTREAMS.bak" 2>/dev/null || true
  cat >"$UPSTREAMS" <<EOF
# generated by scripts/blue-green.sh at $(date -u +%FT%TZ): live=$1 preview=$2
upstream live    { server app-$1:3000 max_fails=1 fail_timeout=3s; }
upstream preview { server app-$2:3000 max_fails=1 fail_timeout=3s; }
EOF
}
# Validate first; on a bad config keep the previous one (nginx keeps running on the old config either way).
reload_lb() {
  if ! compose exec -T lb nginx -t -q; then
    mv "$UPSTREAMS.bak" "$UPSTREAMS" 2>/dev/null || true
    fail "nginx rejected the new config - traffic unchanged"
  fi
  compose exec -T lb nginx -s reload
}
wait_served() { # <port> <version>: until nginx answers with that version (max 10 s)
  for _ in $(seq 1 50); do
    [ "$(served_version "$1")" = "$2" ] && return 0
    sleep 0.2
  done
  return 1
}

# ---- app colors ---------------------------------------------------------------------------------------------
start_color() { # <color> <version>: 4 containers, returns once every one of them reports ready
  put "$1.version" "$2"
  if [ "$1" = blue ]; then BLUE_VERSION=$2; else GREEN_VERSION=$2; fi
  compose up -d --no-deps --wait --wait-timeout 120 --scale "app-$1=$REPLICAS" "app-$1"
}
drain_realtime() { # <color>: SIGUSR2 = move WebSocket clients away, keep serving HTTP
  compose kill -s SIGUSR2 "app-$1" >/dev/null 2>&1 || true
}
smoke_test() { # <port> <version>: hit several containers through nginx
  for _ in $(seq 1 8); do
    [ "$(served_version "$1")" = "$2" ] || return 1
    curl -sf --max-time 2 "http://localhost:$1/products" >/dev/null || return 1
  done
}

# ---- commands -----------------------------------------------------------------------------------------------
cmd_init() {
  local version=${1:?usage: init <version>}
  compose up -d --wait db
  MIGRATE_VERSION=$version compose run --rm migrate
  start_color blue "$version"
  put live blue
  write_upstreams blue blue
  compose up -d --no-deps lb
  wait_served "$LB_PORT" "$version" || fail "load balancer not serving $version"
  log "live: blue ($version) x $(running blue)"
}

cmd_deploy() {
  local version=${1:?usage: deploy <version>}
  local live idle old t0 t
  live=$(get live)
  [ -n "$live" ] || fail "run init first"
  idle=$(other "$live")
  old=$(get "$live.version")
  t0=$(now_ms)
  log "deploy $version: live=$live($old) -> idle=$idle"

  log "1/5 expand migration with the $version image (additive only, $old keeps working)"
  MIGRATE_VERSION=$version compose run --rm migrate || fail "migration rolled back, nothing else changed"

  log "2/5 start $REPLICAS x $version on $idle, wait until every container is ready"
  t=$(now_ms)
  start_color "$idle" "$version" || {
    compose stop "app-$idle" >/dev/null
    fail "$idle did not become ready - stopped it, live stays $live"
  }
  log "    ready after $(secs_since "$t")s - app containers now: $(app_containers) (budget $((2 * REPLICAS)))"

  log "3/5 smoke test $idle through the preview port"
  write_upstreams "$live" "$idle"
  reload_lb
  if ! smoke_test "$PREVIEW_PORT" "$version"; then
    write_upstreams "$live" "$live"
    reload_lb
    compose stop "app-$idle" >/dev/null
    fail "smoke test failed - stopped $idle, live stays $live"
  fi

  log "4/5 switch live traffic $live -> $idle"
  t=$(now_ms)
  write_upstreams "$idle" "$live"
  reload_lb
  wait_served "$LB_PORT" "$version" || fail "switch not visible on :$LB_PORT"
  put live "$idle"
  put previous "$live"
  log "    switched in $(secs_since "$t")s"

  log "5/5 move realtime users off $live (spread over DRAIN_SECONDS); $live stays up as rollback standby"
  drain_realtime "$live"
  log "DONE in $(secs_since "$t0")s: live=$idle($version), standby=$live($old). Rollback: blue-green.sh rollback"
}

cmd_rollback() {
  local live prev version floor t0
  live=$(get live)
  prev=$(get previous)
  [ -n "$prev" ] || fail "nothing to roll back to"
  version=$(get "$prev.version")
  floor=$(get schema.floor 0)
  [ "$(schema_target_of "$version")" -ge "$floor" ] ||
    fail "$version needs a column dropped by the contract migration - roll forward instead"
  t0=$(now_ms)
  log "rollback: $live -> $prev ($version)"

  if [ "$(running "$prev")" -lt "$REPLICAS" ]; then
    log "standby already removed - starting $REPLICAS x $version on $prev first (~25 s)"
    start_color "$prev" "$version"
  fi
  write_upstreams "$prev" "$live"
  reload_lb
  wait_served "$LB_PORT" "$version" || fail "switch back not visible on :$LB_PORT"
  put live "$prev"
  put previous "$live"
  drain_realtime "$live"
  log "ROLLBACK DONE in $(secs_since "$t0")s: live=$prev($version), standby=$live"
}

cmd_finish() {
  local live old
  live=$(get live)
  old=$(other "$live")
  [ "$(running "$old")" -gt 0 ] || { log "no standby running"; return 0; }
  log "finish: remove standby $old ($(get "$old.version"))"
  write_upstreams "$live" "$live"
  reload_lb
  compose stop -t 60 "app-$old" >/dev/null # SIGTERM -> app drains what is left, then exits
  compose rm -f "app-$old" >/dev/null
  log "app containers now: $(app_containers)"
}

cmd_contract() {
  local color version
  for color in blue green; do
    [ "$(running "$color")" -gt 0 ] || continue
    version=$(get "$color.version")
    [ "$(schema_target_of "$version")" -ge 2 ] ||
      fail "$color still runs $version, which reads the old column - run 'finish' first"
  done
  version=$(get "$(get live).version")
  log "contract migration with $version (SCHEMA_TARGET=3): drop trigger + old column"
  MIGRATE_VERSION=$version compose run --rm -e SCHEMA_TARGET=3 migrate
  put schema.floor 2 # releases with schema target < 2 can no longer run
}

cmd_status() {
  echo "live=$(get live) previous=$(get previous) schema.floor=$(get schema.floor 0)"
  for color in blue green; do
    echo "  $color: version=$(get "$color.version" -) running=$(running "$color")"
  done
  echo "  :$LB_PORT serves $(served_version "$LB_PORT")  |  :$PREVIEW_PORT serves $(served_version "$PREVIEW_PORT")"
}

cmd=${1:-status}
shift || true
case "$cmd" in
  init | deploy | rollback | finish | contract | status) "cmd_$cmd" "$@" ;;
  *) echo "usage: $0 {init <v>|deploy <v>|rollback|finish|contract|status}" >&2; exit 2 ;;
esac
